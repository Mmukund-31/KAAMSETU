/** Maps backend and recorder error codes to a message in the technician's language. */
export function errorKey(code: string | undefined): StringKey {
  switch (code) {
    case "network_error":
      return "err_network";
    case "speech_rate_limited":
      return "err_busy";
    case "speech_unavailable":
    case "speech_not_configured":
    case "speech_auth_failed":
    case "speech_credit_exhausted":
    case "speech_request_rejected":
      return "err_speech";
    case "no_speech_detected":
      return "err_no_speech";
    case "audio_too_short":
    case "too_short":
      return "err_too_short";
    case "mic_denied":
      return "err_mic_denied";
    case "mic_unavailable":
    case "unsupported_audio_format":
      return "err_mic_unavailable";
    case "duplicate_submission":
      return "err_duplicate";
    default:
      return "err_generic";
  }
}
